// สิบหกหน้าเรียกอ่านกระเป๋า และแต่ละครั้งอ่าน Firestore ใหม่ทั้งหมด
// เดินจากหน้าหลักไปจัดทีมแล้วไปอุปกรณ์ คืออ่านตัวละครทั้งกระเป๋าสามรอบ
// ทั้งที่ข้อมูลไม่ได้เปลี่ยนเลย ซึ่งกินโควตาและทำให้ทุกหน้าหน่วงตอนเปิด
//
// แยกไฟล์นี้ออกมาเพราะทั้ง player.js และ gear.js ต้องใช้
// ถ้าเก็บไว้ในไฟล์ใดไฟล์หนึ่ง สองไฟล์จะนำเข้ากันไปมาเป็นวง
// ซึ่งทำงานได้แต่เปราะ และพังแบบหาสาเหตุยากเมื่อลำดับการโหลดเปลี่ยน
//
// เก็บผลไว้สั้น ๆ แล้วล้างทิ้งทันทีที่มีการเขียน
// ไม่เก็บนานกว่านี้เพราะข้อมูลที่เก่าเกินไปอันตรายกว่าการอ่านซ้ำ
// ─────────────────────────────────────────────────────────────

const CACHE_MS = 20000
let cache = { uid: null, data: null, at: 0 }

export function readCache(uid) {
  if (cache.uid === uid && Date.now() - cache.at < CACHE_MS) return cache.data
  return null
}

export function writeCache(uid, data) {
  cache = { uid, data, at: Date.now() }
  return data
}

/** ล้างแคชทิ้ง เรียกทุกครั้งหลังเขียนอะไรที่กระทบกระเป๋าตัวละคร */
export function invalidateRoster() {
  cache = { uid: null, data: null, at: 0 }
}
