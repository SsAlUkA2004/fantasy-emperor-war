// ชื่อที่เอาไว้โชว์
//
// ชื่อผู้ใช้ (username) เป็น a-z 0-9 ขีดล่าง เท่านั้น เพราะระบบสมัครแปลงมันเป็นอีเมลหลอก
// ให้ Firebase Auth บังคับความไม่ซ้ำแทนเรา (ดู lib/auth.js) พิมพ์ไทยไม่ได้และห้ามเปลี่ยนตลอดชีพ
//
// ชื่อเล่น (nickname) จึงมาเติมส่วนที่ขาด คือเป็นภาษาไทยได้ เปลี่ยนเมื่อไหร่ก็ได้ และไม่ต้องไม่ซ้ำ
// เพราะมันเป็นแค่ชื่อที่เอาไว้โชว์ ไม่ได้ใช้ล็อกอินหรืออ้างอิงตัวตนที่ไหนเลย
//
// กติกาการโชว์:
//   คนอื่นเห็น          — ชื่อเล่นอย่างเดียว ไม่เห็นชื่อผู้ใช้
//   เจ้าตัวเห็นของตัวเอง — "ชื่อเล่น (ชื่อผู้ใช้)" จะได้ยืนยันได้ว่านี่บัญชีเราจริง
//                        และยังจำชื่อผู้ใช้ของตัวเองได้ เพราะต้องใช้ตอนล็อกอิน
//
// ทุกคนที่ยังไม่ตั้งชื่อเล่น (รวมบัญชีเก่าทั้งหมด) ตกมาใช้ชื่อผู้ใช้เหมือนเดิม
// จึงไม่ต้องไล่เขียนข้อมูลย้อนหลังให้ใคร
// ─────────────────────────────────────────────────────────────

export const NICKNAME_MAX = 16

/** ชื่อที่คนอื่นเห็น */
export function displayName(p) {
  const nick = (p?.nickname ?? '').trim()
  return nick || p?.username || 'ไม่ทราบชื่อ'
}

/** ชื่อที่เจ้าของบัญชีเห็นเวลาดูของตัวเอง */
export function selfName(p) {
  const nick = (p?.nickname ?? '').trim()
  if (!nick || !p?.username) return displayName(p)
  return `${nick} (${p.username})`
}

/**
 * ใช้กับรายการที่มีทั้งตัวเราและคนอื่นปนกัน เช่น บอร์ดอันดับ
 * แถวของเราจะมีชื่อผู้ใช้กำกับให้หาตัวเองเจอง่าย ส่วนแถวคนอื่นเห็นแค่ชื่อเล่น
 */
export function nameFor(row, myUid) {
  return row?.uid && row.uid === myUid ? selfName(row) : displayName(row)
}

/**
 * อักขระที่มองไม่เห็น ห้ามให้หลุดเข้าไปในชื่อเล่น
 *
 * เทียบเป็นรหัสตัวเลขตรง ๆ ไม่ใช้ escape แบบ \\u ในนิพจน์ปกติ เพราะถ้าเผลอเขียนเป็นตัวอักษรจริง
 * ลงไฟล์ ตัวคั่นบรรทัด (2028/2029) จะทำให้นิพจน์นั้นพังทั้งไฟล์ โดยไม่มีอะไรเตือนตอนอ่านโค้ด
 */
function invisible(ch) {
  const code = ch.codePointAt(0)
  return (
    code < 0x20 || // อักขระควบคุม
    code === 0x7f || // delete
    (code >= 0x200b && code <= 0x200f) || // ช่องว่างความกว้างศูนย์ กับตัวกำหนดทิศทาง
    code === 0x2028 || // ตัวคั่นบรรทัด
    code === 0x2029 || // ตัวคั่นย่อหน้า
    code === 0xfeff // ช่องว่างกว้างศูนย์แบบไม่ตัดคำ
  )
}

/**
 * ตรวจชื่อเล่นก่อนบันทึก คืนข้อความบอกปัญหา หรือ null ถ้าผ่าน
 * ปล่อยว่างได้ หมายถึงลบชื่อเล่นทิ้งแล้วกลับไปโชว์ชื่อผู้ใช้ตามเดิม
 */
export function validateNickname(value) {
  const s = (value ?? '').trim()
  if (!s) return null
  if (s.length > NICKNAME_MAX) return `ชื่อเล่นยาวได้ไม่เกิน ${NICKNAME_MAX} ตัวอักษร`
  for (const ch of s) {
    if (invisible(ch)) return 'ชื่อเล่นมีอักขระที่ใช้ไม่ได้'
  }
  return null
}

/** ตัดให้พอดีเพดานก่อนเขียนลงฐานข้อมูล กันค่าที่เล็ดลอดมาจากทางอื่น */
export function cleanNickname(value) {
  return (value ?? '').trim().slice(0, NICKNAME_MAX)
}
