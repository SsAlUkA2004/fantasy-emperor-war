/**
 * รอบอัปเดตของบอร์ดอันดับ ทุก 15 นาที
 *
 * บอร์ดไม่มีเซิร์ฟเวอร์คอยส่งข้อมูลสด และใครเปิดตอนไหนก็ได้ข้อมูลตอนนั้น จึงเห็นอันดับไม่ตรงกันเลย
 * แก้ด้วยการแบ่งเวลาเป็นรอบตายตัวตามนาฬิกา (นาทีที่ 00 / 15 / 30 / 45 ของทุกชั่วโมง) ทุกเครื่องนับรอบเดียวกัน
 * ข้อมูลในรอบเดียวกันใช้ซ้ำได้โดยไม่ต้องอ่านใหม่ พอข้ามรอบถึงจะอ่านใหม่ ผลคือเปิดหน้านี้กี่ครั้งใน
 * 15 นาทีก็อ่านฐานข้อมูลแค่ครั้งเดียว และคนที่เปิดค้างไว้ก็ได้อันดับใหม่เองเมื่อถึงรอบ ไม่ต้องกดอะไร
 *
 * นับจากเวลา epoch โดยตรง ไม่ผูกกับเขตเวลา ทุกเขตเวลาที่ชดเชยเป็นทวีคูณของ 15 นาที (รวมประเทศไทย +7)
 * จึงตรงกับนาที 00/15/30/45 บนหน้าปัดนาฬิกาจริง
 */
export const BOARD_REFRESH_MS = 15 * 60 * 1000

/** หมายเลขรอบของเวลานั้น เพิ่มขึ้นทีละหนึ่งทุก 15 นาที */
export function boardSlot(now = Date.now()) {
  return Math.floor(now / BOARD_REFRESH_MS)
}

/** เวลาเริ่มของรอบนั้น (มิลลิวินาที) */
export function slotStart(slot) {
  return slot * BOARD_REFRESH_MS
}

/** อีกกี่มิลลิวินาทีถึงรอบถัดไป */
export function msUntilNextSlot(now = Date.now()) {
  return slotStart(boardSlot(now) + 1) - now
}
