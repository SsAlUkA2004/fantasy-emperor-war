import { RARITIES } from './characters'

/**
 * ชิ้นส่วนที่ได้จากตัวซ้ำหนึ่งตัว
 *
 * ประกาศไว้ในไฟล์ข้อมูล ไม่ใช่ใน lib/gacha.js
 * เพราะไฟล์ข้อมูลไม่ควรต้องดึง firebase เข้ามาเพียงเพื่ออ่านตัวเลขคงที่
 */
export const SHARDS_PER_DUPE = { R: 5, SR: 20, SSR: 50 }

// ─────────────────────────────────────────────────────────────
// หอแลกเปลี่ยน
//
// ตัวซ้ำจากกาชาให้ของสองอย่างพร้อมกัน
//   1. ชิ้นส่วนของตัวนั้นเอง เอาไว้หลอมดาว
//   2. เศษวิญญาณตามระดับหายาก เอาไว้แลกตัวที่ยังไม่มี
//
// ราคาแลกตั้งตามหลัก "ตัวซ้ำสามตัวเท่ากับตัวใหม่หนึ่งตัว"
// ตัวซ้ำ SSR ให้ 50 เศษ สามตัวได้ 150 ซึ่งพอดีกับราคาตัวใหม่
//
// ระดับหายากที่ใช้คิดคือระดับตั้งต้นจากกาชา ไม่ใช่ระดับหลังยกระดับ
// ไม่งั้นจะกลายเป็นวงจรปั่นเศษ SSR จากตัว R ที่ปั้นขึ้นมา
// ─────────────────────────────────────────────────────────────

export const DUPES_PER_UNIT = 3

export const EXCHANGE_COST = RARITIES.reduce((acc, r) => {
  acc[r] = SHARDS_PER_DUPE[r] * DUPES_PER_UNIT
  return acc
}, {})

export const EMPTY_POOL = { R: 0, SR: 0, SSR: 0 }

export const POOL_NAMES = {
  R: 'เศษวิญญาณสามัญ',
  SR: 'เศษวิญญาณหายาก',
  SSR: 'เศษวิญญาณตำนาน',
}

export const POOL_MARKS = { R: '🔹', SR: '🔷', SSR: '🔶' }

/** เพดานเศษที่ได้จากการสุ่มหนึ่งชุด ใช้ให้กฎตรวจว่าตัวเลขเป็นไปได้จริง */
export function maxPoolGain(pullCount) {
  return SHARDS_PER_DUPE.SSR * pullCount
}
