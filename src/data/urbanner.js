import { CHARACTERS } from './characters'

// ─────────────────────────────────────────────────────────────
// ตู้ UR — ตู้กาชาใหม่ที่มีระดับความหายากสูงสุดของเกม
//
// แยกไฟล์จาก characters.js เหมือนตู้ธาตุ (elemental.js) เก็บแค่รายชื่อ/อัตราของตู้นี้
// ตัวข้อมูลตัวละครสิบเอ็ดตัวยังอยู่ในออบเจ็กต์ CHARACTERS ปกติ เพื่อให้ระบบอื่น
// (เลเวล ยกระดับ สนามรบ หอสะสม) ใช้งานตัวเหล่านี้ได้เหมือนตัวปกติทุกอย่าง
//
// ระดับ UR ไม่อยู่ใน RARITIES (R/SR/SSR) ของระบบยกระดับ เพราะไม่ใช่ปลายทางที่ตัวอื่น
// ไต่ขึ้นมาได้ และตัวมันเองก็ไต่ขึ้นไปที่ไหนต่อไม่ได้อีก ตั้งใจให้ได้จากตู้นี้เท่านั้น
// ผลคือถูกกรองออกจากดันเจี้ยนรอยอดีตและหอแลกเปลี่ยนโดยอัตโนมัติ เพราะทั้งสองระบบนั้น
// สร้างกองตัวละครจาก BY_RARITY ที่วนตาม RARITIES เท่านั้น (ดู characters.js)
//
// ตัวระดับ SR/SSR แปดตัวในตู้นี้ไม่ได้ผูกการันตีพิเศษอะไร จึงยังโผล่ในดันเจี้ยนรอยอดีต
// และหอแลกเปลี่ยนได้ตามปกติเหมือนตัวละครทั่วไประดับเดียวกัน มีแค่ระดับ UR เท่านั้นที่ผูกขาด
// ─────────────────────────────────────────────────────────────

export const UR_BANNER_IDS = {
  SR: ['pyros', 'terrak', 'ventia', 'umbrose', 'solvane'],
  SSR: ['aurex', 'nerissa', 'gaiannon'],
  UR: ['nyxaroth', 'elyria', 'abyssara'],
}

export const ALL_UR_BANNER_IDS = [
  ...UR_BANNER_IDS.SR,
  ...UR_BANNER_IDS.SSR,
  ...UR_BANNER_IDS.UR,
]

/** ไม่มีการันตีเลยทั้งตู้ รวมถึงระดับ UR — สุ่มอิสระทุกครั้งตามอัตรานี้ตรง ๆ */
export const UR_RATES = { SR: 0.8, SSR: 0.1995, UR: 0.0005 }

/** กองตัวละครของตู้นี้ แบ่งตามระดับความหายาก รูปแบบเดียวกับ bannerPool ในตู้ปกติ */
export function urBannerPool() {
  return {
    SR: UR_BANNER_IDS.SR.filter((id) => CHARACTERS[id]),
    SSR: UR_BANNER_IDS.SSR.filter((id) => CHARACTERS[id]),
    UR: UR_BANNER_IDS.UR.filter((id) => CHARACTERS[id]),
  }
}
