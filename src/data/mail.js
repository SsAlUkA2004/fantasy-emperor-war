export const MAIL_KINDS = {
  dailyRank: 'รางวัลประจำวันตามแรงค์',
  season: 'รางวัลปลายฤดูกาล',
  system: 'จากระบบ',
}

/** เพชรที่ได้ต่อวันตามแรงค์ ยิ่งแรงค์สูงยิ่งได้มาก */
export const DAILY_RANK_GEMS = [10, 25, 45, 70, 100, 140, 200]

export function dailyGemsFor(rankIndex = 0) {
  return DAILY_RANK_GEMS[Math.min(rankIndex, DAILY_RANK_GEMS.length - 1)]
}

/** รหัสจดหมายรางวัลประจำวัน หนึ่งฉบับต่อหนึ่งวัน */
export function dailyMailId(dayKey) {
  return `daily-${dayKey}`
}
